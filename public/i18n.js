// A language the visitor chose is also kept in a cookie, so the server
// renders pages in it.
const rememberLang = (lang) => {
  document.cookie = `fp_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
};

function detectLang() {
  // An explicit ?lang= in the address wins (search engines index those URLs)
  // and is remembered like a choice made with the CS/EN switch.
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(fromUrl)) {
    try {
      localStorage.setItem(LANG_KEY, fromUrl);
    } catch {
      /* storage unavailable */
    }
    rememberLang(fromUrl);
    return fromUrl;
  }
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) {
      if (!document.cookie.includes(`fp_lang=${saved}`)) rememberLang(saved);
      return saved;
    }
  } catch {
    /* storage unavailable */
  }
  for (const lang of navigator.languages || [navigator.language || '']) {
    const code = String(lang).toLowerCase();
    if (code.startsWith('cs') || code.startsWith('sk')) return 'cs';
    if (code.startsWith('en')) return 'en';
  }
  return 'en';
}

const LANG = detectLang();

function t(key, vars = {}) {
  const template = I18N[LANG][key] ?? I18N.cs[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

function setLang(lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage unavailable */
  }
  rememberLang(lang);
  const url = new URL(location.href);
  if (url.searchParams.has('lang')) {
    url.searchParams.set('lang', lang);
    location.href = url.href;
  } else {
    location.reload();
  }
}

// Fills every element marked with data-i18n* attributes, and shows only the
// [data-lang] blocks of the current language.
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-lang]')) el.hidden = el.dataset.lang !== LANG;
}

applyI18n();

// CS / EN toggle.
// The server renders the buttons; this marks the current one and makes them work.
for (const button of document.querySelectorAll('[data-lang-switch] [data-set-lang]')) {
  const lang = button.dataset.setLang;
  button.setAttribute('aria-pressed', String(lang === LANG));
  button.addEventListener('click', () => lang !== LANG && setLang(lang));
}

// The brand is simply the domain this runs on.
for (const el of document.querySelectorAll('[data-brand]')) {
  const host = location.hostname.replace(/^www\./, '');
  const dot = host.indexOf('.');
  el.replaceChildren(dot > 0 ? host.slice(0, dot) : host);
  if (dot > 0) el.append(Object.assign(document.createElement('span'), { className: 'tld', textContent: host.slice(dot) }));
}

